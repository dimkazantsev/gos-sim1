-- Disposable local Supabase integration schema. Never apply to production.
CREATE TABLE public.games (
 id uuid PRIMARY KEY,
 title text NOT NULL,
 game_code text NOT NULL UNIQUE,
 owner_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 status text NOT NULL DEFAULT 'lobby',
 current_round integer NOT NULL DEFAULT 1,
 turn_open boolean NOT NULL DEFAULT false,
 settings jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.game_members (
 game_id uuid NOT NULL REFERENCES public.games(id) ON DELETE CASCADE,
 user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 full_name text NOT NULL,
 kind text NOT NULL,
 PRIMARY KEY(game_id,user_id)
);
CREATE TABLE public.blitz_questions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 topic text NOT NULL,
 question text NOT NULL,
 options jsonb NOT NULL,
 correct_index integer NOT NULL,
 legal_act text NOT NULL,
 article text NOT NULL,
 source_url text NOT NULL,
 explanation text NOT NULL,
 verified boolean NOT NULL DEFAULT true
);
CREATE TABLE public.blitz_assignments (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 game_id uuid NOT NULL REFERENCES public.games(id) ON DELETE CASCADE,
 user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 question_id bigint NOT NULL REFERENCES public.blitz_questions(id),
 stage_no integer NOT NULL,
 assigned_day date NOT NULL DEFAULT current_date,
 available_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 started_at timestamptz,
 answered_at timestamptz,
 chosen_index integer,
 is_correct boolean
);
ALTER TABLE public.blitz_assignments ENABLE ROW LEVEL SECURITY;
CREATE POLICY blitz_assignment_owner_read ON public.blitz_assignments
 FOR SELECT TO authenticated USING ((select auth.uid())=user_id);
GRANT SELECT ON public.blitz_assignments TO authenticated;
