-- Formal institutions / NPA registry.
create sequence if not exists public.formal_registry_seq;

create table if not exists public.formal_documents(
  id uuid primary key default gen_random_uuid(),
  game_id uuid not null references public.games(id) on delete cascade,
  stage_no integer not null default 12 check(stage_no between 1 and 16),
  registry_no text not null unique,
  title text not null,
  doc_type text not null,
  subject_key text not null,
  subject_label text not null,
  author_id uuid not null references auth.users(id) on delete cascade,
  body_text text,
  source_file_path text,
  source_file_name text,
  source_mime_type text,
  workflow_key text not null,
  workflow_steps jsonb not null,
  current_step integer not null default 0,
  status_code text not null default 'draft',
  status_label text not null default 'Черновик',
  current_owner_key text not null default 'author',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists formal_documents_game_idx on public.formal_documents(game_id,updated_at desc);
create index if not exists formal_documents_author_idx on public.formal_documents(author_id);
create index if not exists formal_documents_stage_idx on public.formal_documents(game_id,stage_no,status_code);
alter table public.formal_documents enable row level security;
grant select on public.formal_documents to authenticated;
drop policy if exists formal_documents_read on public.formal_documents;
create policy formal_documents_read on public.formal_documents for select to authenticated using(private.is_game_member(game_id));

create table if not exists public.formal_document_history(
  id bigint generated by default as identity primary key,
  document_id uuid not null references public.formal_documents(id) on delete cascade,
  game_id uuid not null references public.games(id) on delete cascade,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  from_status text,
  to_status text,
  from_owner text,
  to_owner text,
  note text,
  created_at timestamptz not null default now()
);
create index if not exists formal_history_doc_idx on public.formal_document_history(document_id,created_at);
create index if not exists formal_history_game_idx on public.formal_document_history(game_id,created_at desc);
alter table public.formal_document_history enable row level security;
grant select on public.formal_document_history to authenticated;
drop policy if exists formal_history_read on public.formal_document_history;
create policy formal_history_read on public.formal_document_history for select to authenticated using(private.is_game_member(game_id));

