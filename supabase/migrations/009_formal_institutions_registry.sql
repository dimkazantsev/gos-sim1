drop policy if exists game_assets_formal_insert on storage.objects;
create policy game_assets_formal_insert on storage.objects for insert to authenticated
with check(bucket_id='game-assets' and split_part(name,'/',2)='formal' and private.is_game_member((split_part(name,'/',1))::uuid));

do $$
begin
 if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='formal_documents') then
  alter publication supabase_realtime add table public.formal_documents;
 end if;
 if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='formal_document_history') then
  alter publication supabase_realtime add table public.formal_document_history;
 end if;
end $$;
