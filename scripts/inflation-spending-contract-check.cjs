const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const migrations=fs.readdirSync(path.join(root,'supabase/migrations'));
const name=migrations.find(x=>x.endsWith('_automatic_inflation_on_confirmed_spending_20261122.sql'));
assert(name,'Committed inflation migration must exist');
const sql=fs.readFileSync(path.join(root,'supabase/migrations',name),'utf8');
const macro=fs.readFileSync(path.join(root,'components/game/FiscalMacroPanel.tsx'),'utf8');
const requireText=(s,re,label)=>assert.match(s,re,label);
requireText(sql,/private\.apply_inflation_from_fiscal_ledger/, 'Event and macro spending is handled server side');
requireText(sql,/private\.apply_inflation_from_published_budget/, 'Published budget and programs are handled');
requireText(sql,/DEFERRABLE INITIALLY DEFERRED/, 'Budget change runs after document publication');
requireText(sql,/OLD\.status IS DISTINCT FROM NEW\.status/, 'No reapplication on repeated publication');
requireText(sql,/NEW\.source_type IN \('event','budget_transfer','act'\)/, 'Only actual ledger spending sources');
requireText(sql,/NEW\.before_values->'inflation'\) IS NOT DISTINCT FROM/, 'Manual inflation is not overwritten');
requireText(sql,/p_spending_delta\*20\/44069700/, 'Single 2026 expense reference');
requireText(sql,/greatest\(-\.5,least\(\.5/, 'Per decision inflation cap');
requireText(sql,/REVOKE ALL ON FUNCTION private\.apply_spending_inflation/, 'No direct unauthorised invocation');
requireText(sql,/source_id=v_id AND region_code='00'/, 'Idempotent existing fiscal ledger used');
requireText(sql,/WHERE item->>'key'<>'13'/, 'Interest is excluded from spending effect');
requireText(sql,/items_amount/, 'State programs only enter on adopted spending');
requireText(macro,/key==='inflation'&&<small>Преподаватель/, 'Teacher control remains explained');
requireText(macro,/data-inflation-explanation/, 'Existing student explanation');
requireText(macro,/g\.teacher\|\|key==='key_rate'/, 'Teacher edit permission unchanged');
const effect=money=>Math.max(-.5,Math.min(.5,Math.round(money*20/44069700*1e8)/1e8));
assert.equal(effect(100000),.04538266);
assert.equal(effect(-100000),-.04538266);
assert.equal(effect(3000000),.5);
