// Focused regression for institutional acting capacity and no artificial classroom voting filters.
const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript'),vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const profile=read('components/game/ProfileOffices.tsx');
const votes=read('components/game/VotesView.tsx');
const attendance=read('components/game/InstitutionRegistrationPanel.tsx');
const docs=read('components/game/DocumentsView.tsx');
const form=read('components/game/StageDocumentForm.tsx');
const migration=read('supabase/migrations/20261015010000_contextual_document_office_validation.sql');
assert(!profile.includes('select_game_office')&&!profile.includes('officeCurrentRole'),'Student cannot switch the representative role in profile');
assert(profile.includes('Полномочия действуют')&&profile.includes('active.length'),'Role portfolio is visible in profile');
assert(!votes.includes('label="Учебная группа"')&&!attendance.includes('label="Учебная группа"'),'No classroom group filter is displayed');
assert(!votes.includes('groupName:group||null')&&!attendance.includes('m.group_name===group'),'Groups cannot restrict a new voting procedure');
assert(votes.includes("groupName:null"),'Votes are opened without a group boundary');
assert(attendance.includes("eligible(m.user_id)"),'Attendance is based on actual institutional membership');
assert(docs.includes('acting_office_id:actingOffice?.id')&&form.includes('acting_office_id:actingOffice?.id'),'Both document creation paths capture the acting office');
assert(docs.includes('От чьего имени оформляется документ')&&form.includes('От чьего имени оформляется документ'),'Role choice occurs per action');
assert(docs.includes('const attributedUser=selected?.metadata?.acting_user_id'),'Signature reflects recorded representative');
assert(migration.includes('private.validate_document_acting_office'),'Provenance trigger is present');
assert(migration.includes("status='active'")&&migration.includes("errcode='42501'"),'Selected office must be active, authorized and subject-compatible');
assert(migration.includes('not private.is_game_teacher(o.game_id)'),'Student role switching blocked at server RPC');
const source=read('components/game/contextualOffices.ts');
let exported={};
const transpiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const ctx={exports:exported,require:id=>id==='./formalInstitutions'?{FORMAL_SUBJECTS:[]}:{}};
vm.runInNewContext(transpiled,ctx);
const match=ctx.exports.officeSupportsSubject;
assert(match('Депутат Государственной Думы','gd_deputy'));
assert(!match('Депутат Государственной Думы','ministry'));
assert(match('Министр финансов','ministry'));
assert(!match('Министр финансов','president'));
assert(match('Президент Российской Федерации','president'));
assert(!match('Сенатор Совета Федерации','gd_deputy'));
console.log('PASS role portfolio, contextual signatures, safe appointments, and no classroom voting groups');
