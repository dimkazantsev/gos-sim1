const base={id:'post',game_id:'game-a',source_key:'stage:abc:completed:2026',context:{automatic:true,source_table:'game_stages',stage_no:4,stage_title:'Первое заседание Государственной Думы'},title:'Завершён этап 4: Первое заседание Государственной Думы',body:'Избрать руководство ГД, создать пять комитетов'};
