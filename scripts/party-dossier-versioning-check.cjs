const assert=require('node:assert/strict'),fs=require('node:fs');
const ts=require('typescript');
const source=fs.readFileSync('components/game/partyDocumentVersions.ts','utf8');
const output=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const exports={};new Function('exports',output)(exports);
const {partyLatestDocuments,partyVersionLabel,partyLatestAccepted}=exports;
const d=(kind,version,status)=>({id:kind+version,doc_kind:kind,version_no:version,status,created_at:'2026-10-15'});
const originals=[d('charter',1,'accepted'),d('charter',2,'revision'),d('program',1,'accepted')];
const latest=partyLatestDocuments(originals);
assert.equal(latest.length,2);
assert.equal(latest.find(x=>x.doc_kind==='charter').version_no,2);
assert.equal(partyVersionLabel(latest[0]).startsWith('В'),true);
assert.equal(partyLatestAccepted(originals,['charter','program']),false);
assert.equal(partyLatestAccepted([...originals,d('charter',3,'accepted')],['charter','program']),true);
assert.equal(partyLatestAccepted([...originals,d('charter',3,'submitted')],['charter','program']),false);
