const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),Module=require('node:module'),ts=require('typescript');
const root=path.join(__dirname,'..');
const original=Module._resolveFilename;
Module._resolveFilename=function(request,...args){return original.call(this,request.startsWith('@/')?path.join(root,request.slice(2)):request,...args)};
require.extensions['.css']=module=>{module.exports={}};
for(const ext of ['.ts','.tsx'])require.extensions[ext]=(module,file)=>module._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJS,esModuleInterop:true,target:ts.ScriptTarget.ES2022},fileName:file}).outputText,file);
const React=require('react');
const {renderToStaticMarkup}=require('react-dom/server');
const Choice=require('../components/game/EventChoicePanel').default;
const Collab=require('../components/game/EventCollaboration').default;
const mockMember=i=>({game_id:'game',user_id:'student-'+i,kind:'student',full_name:'Студент '+i,role_title:i===2?'Министр юстиции':'Депутат Государственной Думы',roster_archived_at:null});
const members=Array.from({length:40},(_,i)=>mockMember(i+1));
members[39].roster_archived_at='2026-10-19T00:00:00Z';
const render=(Component,props)=>renderToStaticMarkup(React.createElement(Component,props));
const labels=['Вариант А','Проверить законность и оформить документы','Вариант В'];
const choiceProps={labels,decisions:[{actor_id:'student-1',choice:'option_1'}],members,profiles:[],currentChoice:'option_1',canAnswer:false,onAnswer:()=>{},revealResults:true,shuffleSeed:'case-game',correctIndex:1,showLegalFeedback:false};
const closed=render(Choice,choiceProps);
assert.match(closed,/data-best-option="true"/);
assert.equal((closed.match(/class="eventAnswerBestLabel"/g)||[]).length,1);
assert.match(closed,/Наиболее обоснованный вариант/);
assert.match(closed,/eventAnswerOption is-correct/);
assert.match(closed,/eventAnswerOption is-incorrect/);
const best=closed.match(/<div class="eventAnswerOption is-correct"[^>]*>[\s\S]*?<span class="eventAnswerHeading"><b>([^<]+)<\/b>/);
assert.equal(best?.[1],labels[1],'The original index must survive visual shuffling');
const before=render(Choice,{...choiceProps,revealResults:false});
assert.doesNotMatch(before,/data-best-option|eventAnswerBestLabel|is-correct/,'No spoilers before results become visible');
const unread=render(Choice,{...choiceProps,correctIndex:null});
assert.doesNotMatch(unread,/data-best-option|eventAnswerBestLabel|is-correct/,'Unknown answer must never be guessed');
const g={game:{id:'game'},me:members[0],members,teacher:false,names:{}};
const collabProps={g,caseId:'case',invitations:[],assignedIds:['student-1','student-2'],closed:false,votingStarted:false,onChanged:async()=>{}};
const collab=render(Collab,collabProps);
assert.match(collab,/Кого пригласить к рассмотрению ситуации/);
assert.match(collab,/Студент 3/);
assert.doesNotMatch(collab,/<option[^>]*value="student-1"/);
assert.doesNotMatch(collab,/<option[^>]*value="student-2"/);
assert.doesNotMatch(collab,/<option[^>]*value="student-40"/);
assert.equal((collab.match(/<option value="student-/g)||[]).length,37,'Show eligible participants, not assigned or archived members');
assert.match(collab,/Обновить список/);
const small={...g,members:[members[0],members[1]]};
const empty=render(Collab,{...collabProps,g:small});
assert.match(empty,/Нет доступных участников/);
assert.match(empty,/Пригласить пока некого/);
assert.match(empty,/disabled=""/);
const css=fs.readFileSync(path.join(root,'app/2026-collaboration.css'),'utf8');
assert(css.includes('.eventAnswerPanel .eventAnswerOption.is-correct>.eventAnswerChoice'));
assert(css.includes('background:#eaf8ef!important'));
assert(css.includes('.eventInviteControls>.eventInviteEmpty'));
console.log('PASS: correct best answer green after result, no premature spoilers, role list with 40 incl archived, empty roster explained, update action, CSS.');
