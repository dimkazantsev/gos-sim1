'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const source=fs.readFileSync('components/game/profileEmailDelivery.ts','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const moduleExports={};
new Function('exports',compiled)(moduleExports);
const {describeProfileEmailError:explain,EMAIL_RATE_LIMIT_COOLDOWN_MS,EMAIL_RESEND_GUARD_MS}=moduleExports;
const throttled=explain({status:429,code:'over_email_send_rate_limit',message:'Email rate limit exceeded'});
assert.equal(throttled.kind,'rate_limit');
assert.equal(throttled.cooldownMs,60*60*1000);
assert(throttled.notice.includes('десять немедленных повторов не помогут'));
const existing=explain({status:422,code:'email_exists',message:'A user with this email address has already been registered'});
assert.equal(existing.kind,'email_exists');
assert.equal(existing.cooldownMs,0);
assert(existing.notice.includes('уже зарегистрирован'));
const blocked=explain({status:400,code:'email_address_not_authorized',message:'Email address not authorized'});
assert.equal(blocked.kind,'not_authorized');
assert(blocked.notice.includes('SMTP'));
const fallback=explain({status:500,message:'Temporary server error'});
assert.equal(fallback.kind,'other');
assert(fallback.notice.includes('Temporary server error'));
const generic429=explain({status:429,message:'Too many requests'});
assert.equal(generic429.kind,'rate_limit');
assert.equal(EMAIL_RATE_LIMIT_COOLDOWN_MS,60*60*1000);
assert.equal(EMAIL_RESEND_GUARD_MS,60*1000);
const view=fs.readFileSync('components/game/ProfileSecurityPanel.tsx','utf8');
assert(view.includes('describeProfileEmailError(r.error)'),'Auth failure must be classified');
assert(view.includes('Date.now()<emailRetryUntil'),'Retry cooldown must prevent network requests');
assert(view.includes('window.localStorage.setItem'),'Cooldown must survive a reload in this browser');
assert(view.includes('disabled={busy||verified||!email.includes(\'@\')||retryMinutes>0}'),'Sending disabled during cooldown');
assert(view.includes('disabled={busy} onClick={()=>void check()}'),'Checking existing verification must remain available');
assert(view.includes('supabase.auth.updateUser({email:requestedEmail}'),'Keep existing Supabase verification flow');
assert(view.includes('setNotice(\'Письмо отправлено на \'+requestedEmail'),'Success must be reported only on acceptance');
assert(!view.includes('for(let retry'),'No automatic burst retries on HTTP 429');
console.log('PASS: Auth 429, pre-existing account, SMTP restriction, retry cooldown and verification checks');
